import { design } from '../src/core/design';
import { scorePackage } from './metrics';
import { getProfile } from './profiles';
const [garment, styleId, materialId, profile = 'petite-hourglass', opts = '{}'] = process.argv.slice(2);
const req = { measurements: getProfile(profile).measurements, garment: garment as never, styleId, materialId, options: JSON.parse(opts) };
const pkg = design(req);
for (const r of scorePackage(req, pkg, true)) if (r.score < 1) console.log(r.id, r.score, r.details.join(' | '));
console.log('closure', pkg.fit.options.closure, JSON.stringify(pkg.fit.finished), JSON.stringify(pkg.fit.ease));
for (const p of pkg.pieces) console.log(p.id, p.layer, p.edges.map((e) => `${e.id}:${e.kind}:${e.lengthCm.toFixed(1)}`).join(' '));
console.log(pkg.quality.filter((q) => !q.ok).map((q) => q.id + ': ' + q.message).join('\n'));
console.log(pkg.bom.map((b) => `${b.kind} ${b.name} ${b.quantity}${b.unit} ${b.essential ? '' : '(opt)'}`).join('\n'));
